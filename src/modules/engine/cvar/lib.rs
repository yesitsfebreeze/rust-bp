//! Console variables: a struct of numbered fields that code reads directly, which
//! the console and a TOML config also address by name. Every cvar is a number;
//! switches use 0 and 1.
//!
//! Declare a set with [`cvars!`]; the generated struct implements [`Registry`]:
//!
//! ```
//! cvar::cvars! {
//!     /// Tunables.
//!     pub struct Settings {
//!         sv_gravity = 800.0, "World gravity, units/s².";
//!         fov = 90.0, "Field of view, degrees.";
//!     }
//! }
//! use cvar::Registry;
//! let mut s = Settings::default();
//! s.set("fov", 110.0).unwrap();
//! assert_eq!(s.fov, 110.0);
//! ```

use std::fmt::Write;

/// Name-based access to a set of cvars, generated by [`cvars!`].
pub trait Registry: Default {
	/// Names in declaration order.
	const NAMES: &'static [&'static str];

	fn get(&self, name: &str) -> Option<f32>;
	fn slot(&mut self, name: &str) -> Option<&mut f32>;
	fn help(name: &str) -> Option<&'static str>;
	fn default_value(name: &str) -> Option<f32>;

	/// Sets a cvar, rejecting unknown names and non-finite values.
	fn set(&mut self, name: &str, value: f32) -> Result<(), String> {
		if !value.is_finite() {
			return Err(format!("{name}: {value} is not a finite number"));
		}
		let slot = self
			.slot(name)
			.ok_or_else(|| format!("unknown cvar \"{name}\""))?;
		*slot = value;
		Ok(())
	}

	fn reset(&mut self, name: &str) -> Result<(), String> {
		let value = Self::default_value(name).ok_or_else(|| format!("unknown cvar \"{name}\""))?;
		self.set(name, value)
	}

	/// Applies a TOML document of `name = number` pairs; booleans count as 1 and 0.
	/// Known keys are applied even when others fail; each failure is returned as a
	/// message. A document that does not parse changes nothing.
	fn apply_toml(&mut self, text: &str) -> Result<Vec<String>, String> {
		let table: toml::Table = text
			.parse()
			.map_err(|e: toml::de::Error| e.message().to_owned())?;
		let mut problems = Vec::new();
		for (key, value) in &table {
			let number = match value {
				toml::Value::Float(f) => *f as f32,
				toml::Value::Integer(i) => *i as f32,
				toml::Value::Boolean(b) => *b as u8 as f32,
				other => {
					problems.push(format!(
						"{key}: expected a number, found {}",
						other.type_str()
					));
					continue;
				}
			};
			if let Err(e) = self.set(key, number) {
				problems.push(e);
			}
		}
		Ok(problems)
	}

	/// Every cvar as TOML, each preceded by its help as a comment.
	fn to_toml(&self) -> String {
		let mut out = String::from("# Cvars. Edit here or in the console, then `writeconfig`.\n");
		for name in Self::NAMES {
			let value = self.get(name).unwrap();
			// f32's shortest round-trip form, always a TOML float: `800.0`, `0.022`, `1e20`.
			let _ = write!(
				out,
				"\n# {}\n{name} = {value:?}\n",
				Self::help(name).unwrap()
			);
		}
		out
	}
}

/// Declares a struct of `f32` cvars with defaults and help, implementing
/// [`Registry`] and [`Default`].
#[macro_export]
macro_rules! cvars {
	(
		$(#[$meta:meta])*
		$vis:vis struct $Name:ident {
			$($name:ident = $default:expr, $help:literal;)*
		}
	) => {
		$(#[$meta])*
		#[derive(Clone, Debug, PartialEq)]
		$vis struct $Name {
			$(#[doc = $help] pub $name: f32,)*
		}

		impl Default for $Name {
			fn default() -> $Name {
				$Name { $($name: $default,)* }
			}
		}

		impl $crate::Registry for $Name {
			const NAMES: &'static [&'static str] = &[$(stringify!($name)),*];

			fn get(&self, name: &str) -> Option<f32> {
				match name {
					$(stringify!($name) => Some(self.$name),)*
					_ => None,
				}
			}

			fn slot(&mut self, name: &str) -> Option<&mut f32> {
				match name {
					$(stringify!($name) => Some(&mut self.$name),)*
					_ => None,
				}
			}

			fn help(name: &str) -> Option<&'static str> {
				match name {
					$(stringify!($name) => Some($help),)*
					_ => None,
				}
			}

			fn default_value(name: &str) -> Option<f32> {
				match name {
					$(stringify!($name) => Some($default),)*
					_ => None,
				}
			}
		}
	};
}

#[cfg(test)]
mod tests {
	use super::*;

	cvars! {
		struct Test {
			gravity = 800.0, "Gravity.";
			yaw = 0.022, "Yaw.";
			show = 1.0, "Switch.";
		}
	}

	#[test]
	fn names_round_trip_through_get_and_set() {
		let mut c = Test::default();
		for name in Test::NAMES {
			assert!(Test::help(name).is_some());
			c.set(name, 7.5).unwrap();
			assert_eq!(c.get(name), Some(7.5));
			c.reset(name).unwrap();
			assert_eq!(c.get(name), Test::default_value(name));
		}
		assert!(c.set("nope", 1.0).is_err());
		assert!(c.set("gravity", f32::NAN).is_err());
	}

	#[test]
	fn toml_round_trip_keeps_every_value() {
		let c = Test {
			gravity: 600.0,
			yaw: 0.0165,
			..Test::default()
		};
		let mut d = Test::default();
		assert_eq!(d.apply_toml(&c.to_toml()), Ok(vec![]));
		assert_eq!(c, d);
	}

	#[test]
	fn toml_reports_bad_keys_and_keeps_good_ones() {
		let mut c = Test::default();
		let problems = c
			.apply_toml("gravity = 400\nshow = false\nbogus = 1\nyaw = \"wide\"\n")
			.unwrap();
		assert_eq!((c.gravity, c.show), (400.0, 0.0));
		assert_eq!(problems.len(), 2, "{problems:?}");
		assert!(c.apply_toml("gravity = ").is_err());
		assert_eq!(c.gravity, 400.0);
	}
}
